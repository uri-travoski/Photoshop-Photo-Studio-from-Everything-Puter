import { srgbProfile, type Curve } from '../src/color/profile';

const sig = (view: DataView, at: number, value: string) =>
  [...value].forEach((c, i) => view.setUint8(at + i, c.charCodeAt(0)));
const xyz = (values: number[]) => {
  const buffer = new ArrayBuffer(20),
    v = new DataView(buffer);
  sig(v, 0, 'XYZ ');
  values.forEach((n, i) => v.setInt32(8 + i * 4, Math.round(n * 65536)));
  return new Uint8Array(buffer);
};
const text = (value: string) => {
  const data = new Uint8Array(28 + value.length * 2),
    view = new DataView(data.buffer);
  sig(view, 0, 'mluc');
  view.setUint32(8, 1);
  view.setUint32(12, 12);
  sig(view, 16, 'enUS');
  view.setUint32(20, value.length * 2);
  view.setUint32(24, 28);
  [...value].forEach((c, i) => view.setUint16(28 + i * 2, c.charCodeAt(0)));
  return data;
};
export function encodeCurve(curve: Curve) {
  if (curve.kind === 'srgb')
    curve = {
      kind: 'parametric',
      type: 3,
      parameters: [2.4, 1 / 1.055, 0.055 / 1.055, 1 / 12.92, 0.04045],
    };
  const count = curve.kind === 'table' ? curve.values.length : curve.parameters.length;
  const data = new Uint8Array(12 + count * (curve.kind === 'table' ? 2 : 4)),
    v = new DataView(data.buffer);
  if (curve.kind === 'table') {
    sig(v, 0, 'curv');
    v.setUint32(8, count);
    curve.values.forEach((n, i) => v.setUint16(12 + i * 2, Math.round(n * 65535)));
  } else {
    sig(v, 0, 'para');
    v.setUint16(8, curve.type);
    curve.parameters.forEach((n, i) => v.setInt32(12 + i * 4, Math.round(n * 65536)));
  }
  return data;
}
// Independent synthetic profiles; no third-party ICC files are redistributed.
export function makeRgbProfile(
  options: {
    matrix?: number[];
    curves?: [Curve, Curve, Curve];
    rawCurve?: Uint8Array;
    extras?: { name: string; data: Uint8Array }[];
  } = {},
) {
  const matrix = options.matrix ?? srgbProfile.matrix;
  const curves = options.curves ?? srgbProfile.curves;
  const tags: { name: string; data: Uint8Array }[] = ['rXYZ', 'gXYZ', 'bXYZ'].map((name, i) => ({
    name,
    data: xyz([matrix[i], matrix[i + 3], matrix[i + 6]]),
  }));
  tags.push({ name: 'wtpt', data: xyz([0.9642, 1, 0.8249]) });
  ['rTRC', 'gTRC', 'bTRC'].forEach((name, i) =>
    tags.push({ name, data: options.rawCurve ?? encodeCurve(curves[i]) }),
  );
  tags.push(...(options.extras ?? []));
  tags.push(
    { name: 'desc', data: text('Synthetic RGB regression profile') },
    { name: 'cprt', data: text('Generated by the Photo Editor test suite') },
  );
  const tableEnd = 132 + tags.length * 12;
  const data = new Uint8Array(
    tableEnd + tags.reduce((n, t) => n + Math.ceil(t.data.length / 4) * 4, 0),
  );
  const v = new DataView(data.buffer);
  v.setUint32(0, data.length);
  v.setUint32(8, 0x04300000);
  [2026, 1, 1, 0, 0, 0].forEach((n, i) => v.setUint16(24 + i * 2, n));
  sig(v, 12, 'mntr');
  sig(v, 16, 'RGB ');
  sig(v, 20, 'XYZ ');
  sig(v, 36, 'acsp');
  v.setUint32(64, 1);
  [0.9642, 1, 0.8249].forEach((n, i) => v.setInt32(68 + i * 4, Math.round(n * 65536)));
  v.setUint32(128, tags.length);
  let offset = tableEnd;
  tags.forEach((tag, i) => {
    sig(v, 132 + i * 12, tag.name);
    v.setUint32(136 + i * 12, offset);
    v.setUint32(140 + i * 12, tag.data.length);
    data.set(tag.data, offset);
    offset += Math.ceil(tag.data.length / 4) * 4;
  });
  return data;
}
